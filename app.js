const cfg = window.AUTOCRAFT || {}

function fill(template, vars) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`))
}

function apply(locale) {
  const dict = I18N[locale] || I18N.en
  document.documentElement.lang = locale
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (!dict[key]) return
    el.textContent = fill(dict[key], { size: cfg.size, platform: cfg.platform, version: cfg.version })
  })
  document.querySelectorAll('.langs button').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === locale)
  })
  localStorage.setItem('autocraft-site-lang', locale)
}

function wire() {
  document.querySelectorAll('[data-download]').forEach((a) => {
    a.href = cfg.downloadUrl || '#'
  })
  document.querySelectorAll('[data-repo]').forEach((a) => {
    a.href = cfg.repoUrl || '#'
  })
  document.querySelectorAll('.langs button').forEach((btn) => {
    btn.addEventListener('click', () => apply(btn.dataset.lang))
  })
  apply('en')
}

