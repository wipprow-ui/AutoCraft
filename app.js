const cfg = window.AUTOCRAFT || {}

function fill(template, vars) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`))
}

function keysOf(dict) {
  return Object.keys(dict).sort()
}

function apply(locale) {
  const dict = I18N[locale] || I18N.en
  const vars = { size: cfg.size, platform: cfg.platform, version: cfg.version }
  document.documentElement.lang = locale
  document.title = fill(dict.pageTitle, vars)
  const desc = document.querySelector('meta[name="description"]')
  if (desc) desc.setAttribute('content', fill(dict.pageDesc, vars))
  const ogTitle = document.querySelector('meta[property="og:title"]')
  if (ogTitle) ogTitle.setAttribute('content', fill(dict.pageTitle, vars))
  const ogDesc = document.querySelector('meta[property="og:description"]')
  if (ogDesc) ogDesc.setAttribute('content', fill(dict.pageDesc, vars))
  const ogLocale = document.querySelector('meta[property="og:locale"]')
  if (ogLocale) ogLocale.setAttribute('content', locale === 'ru' ? 'ru_RU' : locale === 'de' ? 'de_DE' : 'en_US')
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (!dict[key]) return
    el.textContent = fill(dict[key], vars)
  })
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria')
    if (dict[key]) el.setAttribute('aria-label', fill(dict[key], vars))
  })
  document.querySelectorAll('.langs button').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === locale)
  })
  localStorage.setItem('autocraft-site-lang', locale)
}

function wire() {
  document.querySelectorAll('[data-download]').forEach((a) => {
    a.href = cfg.downloadUrl || '#'
  })
  document.querySelectorAll('[data-repo]').forEach((a) => {
    a.href = cfg.repoUrl || '#'
  })
  document.querySelectorAll('.langs button').forEach((btn) => {
    btn.addEventListener('click', () => apply(btn.dataset.lang))
  })
  const saved = localStorage.getItem('autocraft-site-lang')
  apply(I18N[saved] ? saved : 'en')
}

if (typeof window !== 'undefined') {
  const enKeys = keysOf(I18N.en).join('|')
  if (keysOf(I18N.ru).join('|') !== enKeys || keysOf(I18N.de).join('|') !== enKeys) {
    console.warn('AutoCraft i18n: language dictionaries have different keys')
  }
  wire()
}
